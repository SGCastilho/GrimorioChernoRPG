const versionAtLeast=(value,target)=>{const a=String(value||'').split('.').map(Number),b=String(target).split('.').map(Number);for(let i=0;i<Math.max(a.length,b.length);i++){const x=a[i]||0,y=b[i]||0;if(x!==y)return x>y}return true};
const configVersion=(config.match(/APP_VERSION='([^']+)'/)||[])[1];
ok(versionAtLeast(configVersion,'5.39.0'),'versão do config deve ser 5.39.0+');
ok(versionAtLeast(manifest.version,'5.39.0'),'versão do manifest deve ser 5.39.0+');
ok(manifest.deepLinksIntegrated===true&&manifest.nativeNewTabSupport===true,'flags de deep links ausentes no manifest');
